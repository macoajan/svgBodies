// Prueba de interfaz del editor de pautas (Playwright; no forma parte de `npm test`).
//   npm run build && npx vite preview --port 4173 &   y luego   node test/e2e-editor.mjs <carpeta-capturas>
import { createRequire } from 'node:module'; const { chromium } = createRequire(import.meta.url)('playwright');
const out = process.argv[2] || '.', url = process.env.URL || 'http://localhost:4173/';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const pg = await ctx.newPage();
const errs = []; pg.on('pageerror', e => errs.push(e.message)); pg.on('console', m => m.type() === 'error' && errs.push(m.text()));
const shot = n => pg.screenshot({ path: `${out}/${n}.png` });
const ok = (cond, msg) => { console.log(cond ? 'ok ' : 'MAL', msg); if (!cond) process.exitCode = 1; };

await pg.goto(url + '#/pro'); await pg.waitForSelector('h1:has-text("Mis pautas")'); await shot('1-vacio');
await pg.click('button:has-text("+ Nueva")'); await pg.waitForSelector('.titulo-pauta');
await pg.fill('.titulo-pauta', 'Rodilla fase 1');
await pg.selectOption('select', '__nuevo'); await pg.fill('.fila-form input', 'L.G.'); await pg.click('.fila-form button[type=submit]');
await pg.waitForSelector('select'); ok((await pg.$eval('select', s => s.selectedOptions[0].textContent)) === 'L.G.', 'paciente creado y elegido');
await pg.click('a:has-text("+ Añadir ejercicios")'); await pg.waitForSelector('.ficha-mini-sel');
await pg.fill('input[type=search]', 'sentadilla pared'); await pg.waitForTimeout(400); await pg.click('.ficha-mini-sel >> nth=0');
await pg.fill('input[type=search]', 'puente una pierna'); await pg.waitForTimeout(400); await pg.click('.ficha-mini-sel >> nth=0');
await pg.fill('input[type=search]', 'talones'); await pg.waitForTimeout(400);
await pg.click('.ficha-mini a.ficha-mini-meta >> nth=0'); await pg.waitForSelector('.h1-ej');
ok((await pg.textContent('.barra-sel')).includes('2 ya elegidos'), 'la ficha recuerda la selección'); await shot('3-ficha-sel');
await pg.click('.barra-sel .boton'); await pg.waitForSelector('.items');
ok((await pg.$$('.items > li')).length === 3, '3 ejercicios añadidos');
await shot('4-editor');
await pg.click('.item-cab >> nth=1'); await pg.waitForSelector('.item-panel');
await pg.click('button[aria-label="Más series"]'); await pg.fill('#reps-1', '12'); await pg.press('#reps-1', 'Tab');
await pg.fill('.item-panel input[placeholder^="Banda"]', 'Banda roja');
ok((await pg.textContent('.item.abierto .fila-texto span')).startsWith('4 × 12 por lado'), 'dosis actualizada: ' + await pg.textContent('.item.abierto .fila-texto span'));
await shot('5-item');
await pg.click('.item.abierto button:has-text("Subir")'); ok((await pg.textContent('.items > li:first-child strong')).includes('Puente'), 'subir');
// Descanso detrás del primero, con tipo y duración.
await pg.click('.item.abierto button:has-text("+ Descanso detrás")'); await pg.waitForSelector('.item.abierto.item-descanso');
await pg.selectOption('#tipo-1', 'descanso-caminando'); await pg.fill('#dur-1', '120'); await pg.press('#dur-1', 'Tab');
ok((await pg.textContent('.items > li:nth-child(2) strong')) === 'Descanso caminando' && (await pg.textContent('.items > li:nth-child(2) .fila-texto span')).startsWith('2 min'), 'descanso suelto con tipo y duración');
await shot('5b-descanso');
// Series a medida en la sentadilla (ahora 3.ª): 12 repeticiones en la 1.ª y la 3.ª por tiempo.
await pg.click('.item-cab >> nth=2'); await pg.click('.item.abierto .interruptor:has-text("Series a medida")');
await pg.fill('#ps-r-2-0', '12'); await pg.press('#ps-r-2-0', 'Tab');
await pg.click('.item.abierto .serie-fila >> nth=2 >> button:has-text("Por tiempo")');
const dosisSent = await pg.textContent('.item.abierto .fila-texto span');
ok(dosisSent.includes('12/3/30 s'), 'series a medida: ' + dosisSent);
await shot('5c-series');
// Ejercicio por tiempo (talones, 4.º).
await pg.click('.item-cab >> nth=3'); await pg.click('.item.abierto .segmentos.modo button:has-text("Por tiempo")');
ok((await pg.textContent('.item.abierto .fila-texto span')).includes('30 s'), 'ejercicio por tiempo');
await pg.click('button:has-text("+ Añadir descanso")'); ok((await pg.$$('.items > li')).length === 5, 'añadir descanso al final');
await pg.click('.item.abierto button:has-text("Quitar")'); ok((await pg.$$('.items > li')).length === 4, 'quitar el descanso');
ok(!(await pg.$('.aviso.error li')), 'la pauta sigue siendo válida');
await pg.fill('#perWeek', '7'); await pg.press('#perWeek', 'Tab');
await pg.click('.interruptor:has-text("calorías")');
await pg.fill('textarea[placeholder^="Si molesta la rodilla"]', 'Nos vemos el día 24.');
console.log('resumen:', await pg.textContent('.resumen-pauta'));
await pg.waitForTimeout(600); await pg.reload(); await pg.waitForSelector('.items');
ok(await pg.inputValue('.titulo-pauta') === 'Rodilla fase 1', 'título tras recargar');
ok((await pg.textContent('.items > li:first-child .fila-texto span')).includes('Banda roja'), 'carga tras recargar');
ok(await pg.isChecked('.interruptor:has-text("calorías") input'), 'calorías tras recargar');
ok(await pg.inputValue('textarea[placeholder^="Si molesta la rodilla"]') === 'Nos vemos el día 24.', 'mensaje tras recargar');
await pg.evaluate(() => scrollTo(0, 2000)); await shot('6-editor-abajo');
await pg.click('.nav-pro a:has-text("Pautas")'); await pg.waitForSelector('.fila-pauta');
ok((await pg.textContent('.fila-pauta')).includes('Rodilla fase 1 · L.G.'), 'aparece en Mis pautas'); await shot('7-lista');
await pg.fill('input[type=search]', 'puente'); ok((await pg.$$('.fila-pauta')).length === 1, 'búsqueda por ejercicio');
await pg.fill('input[type=search]', 'hombro'); ok((await pg.$$('.fila-pauta')).length === 0, 'búsqueda sin resultados');
await pg.fill('input[type=search]', '');
await pg.click('.fila-pauta'); await pg.waitForSelector('.items'); await pg.click('button:has-text("Duplicar pauta")');
await pg.waitForFunction(() => document.querySelector('.titulo-pauta')?.value.includes('(copia)'));
ok(true, 'pauta duplicada'); await pg.click('button:has-text("Eliminar pauta")'); await pg.click('button:has-text("Sí, eliminar")');
await pg.waitForSelector('h1:has-text("Mis pautas")'); await pg.waitForTimeout(100); ok((await pg.$$('.fila-pauta')).length === 1, 'copia eliminada');
await pg.click('.nav-pro a:has-text("Pacientes")'); await pg.waitForSelector('.fila-pauta'); await pg.waitForTimeout(100); const tp = await pg.textContent('.fila-pauta'); ok(tp.includes('1 pauta'), 'paciente con 1 pauta: ' + tp);
await pg.click('.fila-pauta'); await pg.waitForSelector('text=Nota privada'); await shot('8-paciente');
await pg.setViewportSize({ width: 1194, height: 834 }); await pg.goto(url + '#/pro'); await pg.click('.fila-pauta'); await pg.waitForSelector('.items'); await shot('9-tablet');
console.log('errores:', errs); if (errs.length) process.exitCode = 1;
await b.close();
